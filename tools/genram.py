#!/usr/bin/env python3
"""Generate the C port's RAM layout and ROM symbols from tools/hints.txt.

Writes port/include/bd_ram.h (a 2 KB union: named fields at their NES
addresses, padding elsewhere, every offset checked at compile time) and
port/include/bd_syms.h (#defines for named ROM addresses).

Usage: python tools/genram.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HINTS = os.path.join(ROOT, 'tools', 'hints.txt')
OUT = os.path.join(ROOT, 'port', 'include')


def main():
    ram, rom = [], []
    for line in open(HINTS, encoding='utf-8'):
        m = re.match(r'^\s*(name|sub|code)\s+([0-9A-Fa-f]{4})\s+([A-Za-z_]\w*)(?::(\d+))?\s*(?:#\s*(.*))?$', line)
        if not m:
            continue
        kind, addr, name, size, note = m.groups()
        a = int(addr, 16)
        if kind == 'name' and a < 0x800:
            ram.append((a, name, int(size or 1), (note or '').strip()))
        elif a >= 0x8000:
            rom.append((a, name))
    ram.sort()

    lines = [
        '/* Generated by tools/genram.py from tools/hints.txt -- do not edit. */',
        '#ifndef BD_RAM_H', '#define BD_RAM_H', '', '#include <stddef.h>', '#include <stdint.h>', '',
        '/* NES CPU RAM ($0000-$07FF). Field offsets equal the NES addresses. */',
        'typedef union {', '    uint8_t raw[0x800];', '    struct {',
    ]
    pos = 0
    for a, name, size, note in ram:
        if a < pos:
            raise SystemExit('overlapping RAM fields at $%04X (%s)' % (a, name))
        if a > pos:
            lines.append('        uint8_t _pad_%04X[0x%X];' % (pos, a - pos))
        decl = '        uint8_t %s%s;' % (name, '[%d]' % size if size > 1 else '')
        lines.append('%-48s/* $%04X%s */' % (decl, a, ' ' + note if note else ''))
        pos = a + size
    if pos < 0x800:
        lines.append('        uint8_t _pad_%04X[0x%X];' % (pos, 0x800 - pos))
    lines += ['    };', '} BdRam;', '',
              '_Static_assert(sizeof(BdRam) == 0x800, "RAM layout must be 2 KB");']
    for a, name, size, note in ram:
        lines.append('_Static_assert(offsetof(BdRam, %s) == 0x%04X, "%s");' % (name, a, name))
    lines += ['', '#endif', '']
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'bd_ram.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines))

    syms = ['/* Generated by tools/genram.py from tools/hints.txt -- do not edit. */',
            '#ifndef BD_SYMS_H', '#define BD_SYMS_H', '',
            '/* Named PRG ROM addresses ($8000-$FFFF), for reading tables from the ROM. */']
    seen = set()
    for a, name in sorted(rom):
        if name not in seen:
            seen.add(name)
            syms.append('#define ROM_%s 0x%04X' % (name, a))
    syms += ['', '#endif', '']
    with open(os.path.join(OUT, 'bd_syms.h'), 'w', newline='\n') as f:
        f.write('\n'.join(syms))
    print('bd_ram.h: %d fields; bd_syms.h: %d symbols' % (len(ram), len(seen)))


if __name__ == '__main__':
    main()
